/*
 * ===================================================================
 *  Constant.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 학습용 해석 문서입니다. 이 파일은 "final(상수)은 값을
 *   딱 한 번만 넣을 수 있다"를 보여주려고 일부러 규칙을 어기는
 *   코드를 담고 있어요. 그래서 원본 그대로는 컴파일이 안 되는데,
 *   이건 실수가 아니라 이 파일의 핵심 목적이에요. 파일 맨 위부터
 *   순서대로 짚어보겠습니다.
 *
 *
 * int num1 = 10;
 * final int NUM2 = 20;
 * num1 = 100;
 * NUM2 = 200;
 *
 *   num1(일반 변수)은 나중에 100으로 다시 채워도 아무 문제 없어요.
 *   근데 NUM2는 앞에 final이 붙어 있어서 "값이 고정된 상자"예요.
 *   여기서 컴파일이 막혀요 — "cannot assign a value to final
 *   variable NUM2"라는 오류가 나요. final은 "이 상자는 한 번 채우면
 *   다시 못 바꾼다"는 자바의 안전장치예요.
 *
 *
 * final int NUM3;
 * NUM3 = 300;
 * NUM3 = 3000;
 *
 *   NUM3는 만들 때 바로 값을 안 넣었어요("빈 final") — 이것도
 *   허용돼요. 대신 나중에 딱 한 번만 채울 수 있어요. 300을 넣는
 *   첫 번째 줄은 되지만, 3000을 또 넣는 두 번째 줄에서 다시
 *   막혀요. "선언할 때 바로 채우기"와 "나중에 한 번만 채우기"는
 *   둘 다 결국 "평생 한 번"이라는 같은 규칙의 다른 표현일 뿐이에요.
 *
 *
 * final int PENCIL_PRICE = 1000;
 * final float STUDENT_HEIGHT = 175.5f;
 * final char GRADE = 'A';
 * final String COUNTRY = "Korea";
 *
 *   상수 이름을 대문자+언더바로 쓰는 건 문법 규칙이 아니라 관례예요
 *   — 이렇게 쓰면 "이건 안 바뀌는 값이구나"를 이름만 보고 바로
 *   알 수 있어요.
 *
 *
 * System.out.println("PENCIL_PRICE: %d원" + PENCIL_PRICE);
 *
 *   %d는 printf나 String.format 안에서만 값으로 바뀌는 지정자예요.
 *   println은 문자열을 그냥 이어붙일 뿐이라 %d를 해석하지 않고
 *   글자 그대로 찍어요. 그래서 이 줄을 실행하면 "PENCIL_PRICE:
 *   %d원1000"처럼 %d가 글자로 남고 그 뒤에 숫자가 그냥 붙는,
 *   의도와 다른 모양이 나와요 — 바로 앞 StringFormat.java에서
 *   배운 지정자를 여기서도 쓸 수 있다고 착각한 것으로 보여요.
 *   고치려면 println을
 *   System.out.printf("PENCIL_PRICE: %d원%n", PENCIL_PRICE);
 *   처럼 printf로 바꿔야 해요. 나머지 STUDENT_HEIGHT, GRADE,
 *   COUNTRY 줄도 전부 같은 실수예요.
 *
 *
 * 실행하면 어떻게 될까
 *
 *   원본 그대로는 "NUM2 = 200;"에서 이미 컴파일이 막혀서 한 줄도
 *   실행되지 않아요. 그 실습을 마치고 그 줄을 지운 뒤 진행하면,
 *   NUM3 = 3000; 에서 또 막혀요. 이것도 지우고 나면 마지막
 *   println 4줄이 실행되는데, %d 같은 지정자가 전부 글자 그대로
 *   찍히는 어색한 출력이 나와요.
 */
