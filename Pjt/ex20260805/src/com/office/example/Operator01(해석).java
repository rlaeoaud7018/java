/*
 * ===================================================================
 *  Operator01.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 학습용 해석 문서입니다. 이 파일은 두 군데서 컴파일이
 *   막혀요 — 하나는 진짜 실수(32~33행), 하나는 "이건 안 된다"를
 *   일부러 보여주는 예시(65,67,86,87행)예요. 파일 맨 위부터
 *   순서대로 짚어보겠습니다.
 *
 *
 * int num = 10;
 * let num = 10;	10 == '10' --> true
 * System.out.println("num1 + num2: " + (num1 + num2));
 *
 *   "let"은 자바스크립트에서 변수 만들 때 쓰는 말이에요. 그리고
 *   자바스크립트는 숫자 10과 글자 '10'을 ==로 비교하면 "같다
 *   (true)"고 대충 맞춰줘요. 즉 이 줄은 "자바스크립트는 이렇게
 *   허술하게 비교해준다"는 메모였던 걸로 보여요 (자바는 정반대로,
 *   숫자와 글자를 ==로 비교하는 것 자체를 아예 금지해요). 문제는
 *   "//"를 안 붙여서 진짜 코드로 읽혀버렸다는 거예요 — "let"은
 *   자바에 없는 말이라 여기서 컴파일이 멈춰요. 그 아래 println도
 *   num1, num2를 쓰는데 실제로 만든 건 "num" 하나뿐이라 같이
 *   막혀요.
 *
 *   고치면: "int num = 10;"을 "int num1 = 10;"과 "int num2 = 10;"
 *   두 줄로 바꾸고, "let num = 10; ..." 줄은 지우지 말고
 *   "// let num = 10;  10 == '10' --> true"처럼 주석으로 살려두면
 *   돼요. 메모 내용은 그대로 남기면서 컴파일만 막지 않는 최소
 *   수정이에요.
 *
 *
 * float num3 = 0.1f;
 * float num4 = 0.2f;
 * System.out.println("num3 + num4: " + (num3 + num4));
 *
 *   숫자끼리는 +가 그냥 "더하기"예요.
 *
 *
 * String str1 = "Hello";
 * String str2 = "JAVA";
 * println(str1 + str2);        // HelloJAVA
 * println(10 + "Hello");       // 10Hello
 * println(3.14 + "Hello");     // 3.14Hello
 *
 *   하나라도 문자열이 끼면 +는 "이어붙이기"로 완전히 바뀌어요.
 *   숫자가 문자열을 만나면 자동으로 글자로 바뀐 다음 붙어요.
 *
 *
 * System.out.println("Hello" - "JAVA");  // Exception(Error)
 * System.out.println(10 - "JAVA");       // Exception(Error)
 *
 *   이 파일은 println 옆에 항상 "// 결과값"을 적어두는 습관이
 *   있어요(예: "// -10", "// 30", "// 1"). 이 두 줄도 숫자 대신
 *   "이 줄은 실행이 안 된다"는 뜻으로 "Exception(Error)"를
 *   적어둔 거예요 — 자바의 Exception 클래스를 가리키는 말이
 *   아니라 그냥 "실패"라고 적은 메모라, 이 표시 자체는 고칠 필요
 *   없어요. 다만 알아두면 좋은 게 있는데, 글자에는 -가 아예 없어서
 *   생기는 이 실패는 "실행해보기도 전에" 이미 걸려요(컴파일
 *   오류) — 이건 뒤에 나오는 10/0과 비교하면 차이가 뚜렷해요.
 *
 *
 * System.out.println('A' - 'B');   // -1
 * System.out.println('가' - '나'); // -1176
 *
 *   문자끼리는 -가 돼요. 글자가 안에서는 숫자(유니코드)로
 *   저장되기 때문에, 그 숫자끼리 빼는 거예요.
 *
 *
 * System.out.println(3 * "Hello");   // Exception(Error)
 * System.out.println("Hello" * 3);   // Exception(Error)
 *
 *   -와 마찬가지로 글자에는 *도 없어요. (참고로 파이썬은
 *   "Hello"*3을 "HelloHelloHello"로 허용하지만 자바는 안 돼요 —
 *   바로 아래 원본 주석이 그 차이를 짚고 있어요.)
 *
 *
 * System.out.println(10 / 20);        // 0.5 라고 적혀있지만 실제로는 0
 * System.out.println(10.0f / 20);     // 0.5
 * System.out.println((float)10 / 20); // 0.5
 *
 *   정수(int)끼리 나누면 결과도 무조건 정수예요. 그래서 10/20은
 *   0.5가 아니라 그냥 0이 나와요 — 소수점 아래는 통째로 버려져요.
 *   실수(float)가 하나라도 끼면(10.0f/20, (float)10/20) 그때야
 *   0.5처럼 소수점까지 나와요.
 *
 *
 * System.out.println(10 / 0);
 *
 *   문법은 멀쩡해서 컴파일은 잘 돼요. 근데 실제로 "실행"하는
 *   순간 ArithmeticException이 터져요. 위에서 본 "Hello" - "JAVA"
 *   는 출발도 못 했는데, 이건 출발은 했다가 가다가 넘어지는
 *   거예요 — 발생 시점이 달라요.
 *
 *
 * System.out.println(0 / 100);
 *
 *   반대로 0을 나누는 건 아무 문제 없어요. 결과는 그냥 0이에요.
 *
 *
 * System.out.println(10 % 3);      // 1
 * System.out.println('A' % 'B');   // 65
 *
 *   %는 나눗셈하고 남은 "나머지"만 뽑아요. 'A' % 'B'도 결국
 *   유니코드 숫자끼리의 나머지 계산이에요.
 *
 *
 * System.out.println(10 + 3.14f);
 *
 *   정수와 실수를 더하면 자바가 알아서 정수를 실수로 맞춰서
 *   계산해줘요. 이걸 "산술 변환"이라고 불러요.
 *
 *
 * int no = 10;
 * no = no + 1;
 * no++;
 *
 *   no + 1을 다시 no에 넣는 것도, no++도 결과는 똑같이 1 증가예요.
 *   no++가 더 짧게 쓰는 방법일 뿐이에요.
 *
 *
 * int number = 10;
 * int result = 0;
 * result = (number++);   // result=10, number=11
 * result = ++number;     // result=11, number=11
 *
 *   number++(뒤에 씀)는 "일단 지금 값을 먼저 쓰고, 그다음에 1을
 *   더한다"예요. 그래서 result엔 증가 전 값(10)이 들어가요.
 *   ++number(앞에 씀)는 "먼저 1을 더하고, 그 값을 쓴다"라서
 *   result에 증가 후 값(11)이 들어가요. +가 앞이냐 뒤냐에 따라
 *   결과가 달라지는 거예요.
 *
 *
 * 실행하면 어떻게 될까
 *
 *   32~33행을 고쳐도 65행("Hello" - "JAVA")에서 또 막혀요 — 둘 다
 *   실제 코드로 들어가 있는 이상 컴파일러는 똑같이 오류로 봐요.
 *   65, 67, 86, 87행까지 고치거나 주석 처리해야 나머지(나눗셈,
 *   증감 연산자)까지 끝까지 실행해볼 수 있어요.
 */
