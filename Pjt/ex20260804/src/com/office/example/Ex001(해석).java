/*
 * ===================================================================
 *  Ex001.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 이 파일은 컴파일/실행용이 아닌 학습용 해석 문서입니다.
 *    (Java는 한 패키지 안에 같은 이름의 public 클래스를 둘 이상 둘 수 없고,
 *     "Ex001(해석)"은 괄호가 포함되어 애초에 유효한 클래스 이름도 아니므로,
 *     원본 코드를 실행 가능한 형태로 복제하지 않고 전체를 주석으로 처리했습니다.)
 *
 *
 * -------------------------------------------------------------------
 * 1. 왜 (이 예제의 목적)
 * -------------------------------------------------------------------
 *
 * Java 학습의 첫 단계에서 반드시 거치는 "Hello World" 수준의 예제.
 * 목적은 딱 두 가지이다.
 *   (1) Java 프로그램의 최소 구성 단위인 "클래스(class)"가 무엇이고,
 *       이름을 어떻게 지어야 하는지 규칙을 익히는 것.
 *   (2) JVM이 프로그램을 실행할 때 어디서부터 코드를 읽기 시작하는지,
 *       즉 "진입점(main 메서드)" 개념을 익히는 것.
 *
 *
 * -------------------------------------------------------------------
 * 2. 무엇 (핵심 개념)
 * -------------------------------------------------------------------
 *
 * 비유부터 시작하면, class는 "요리 레시피가 적힌 종이 한 장"과 같다.
 * 레시피(class) 안에는 여러 조리 단계(메서드)가 적혀 있고,
 * 그중 "이 요리는 여기서부터 시작합니다"라고 표시된 단계가 바로 main()이다.
 * JVM(요리사)은 프로그램을 실행할 때 이 표시(main)부터 순서대로 읽어나간다.
 *
 * [클래스 이름 규칙 정리]
 * ---------------------------------------------------------
 * | 예시               | 가능 여부 | 이유                        |
 * |--------------------|-----------|-----------------------------|
 * | Hello              | O         | 영문 대문자로 시작            |
 * | H2ello             | O         | 숫자가 중간에 위치            |
 * | Hello2             | O         | 숫자가 끝에 위치              |
 * | 2Hello             | X         | 숫자로 시작할 수 없음          |
 * | _Hello / H_ello     | O         | '_' 는 특수문자 중 허용        |
 * | $Hello / H$ello     | O         | '$' 는 특수문자 중 허용        |
 * | Hello@ / Hello^^    | X         | '@', '^' 등은 허용되지 않음    |
 * ---------------------------------------------------------
 *
 * [클래스 vs 파일명 vs main()]
 * ---------------------------------------------------------
 * | 구성 요소     | 규칙                                            |
 * |----------------|-------------------------------------------------|
 * | public class   | 파일 하나당 반드시 1개만 존재 가능                  |
 * | 클래스 이름     | public 클래스는 파일명과 반드시 동일해야 함          |
 * | main 메서드     | JVM이 프로그램 실행 시 가장 먼저 호출하는 진입점     |
 * ---------------------------------------------------------
 *
 *
 * -------------------------------------------------------------------
 * 3. 어떻게 (원본 코드 줄 단위 해석)
 * -------------------------------------------------------------------
 *
 * [파일 · 클래스 · 진입점 관계도]
 *
 *   Ex001.java  (파일)
 *       │
 *       └── public class Ex001 { ... }   ← 파일명과 이름 일치 (필수)
 *                 │
 *                 └── public static void main(String[] args) { ... }
 *                           ▲
 *                           └── JVM이 실행 시 가장 먼저 호출하는 지점
 *
 * [원본 1행] package com.office.example;
 *   → 이 클래스가 속한 패키지(폴더 개념) 선언. 실제 디스크 경로
 *     "src/com/office/example/" 와 대응된다.
 *
 * [원본 46행] public class Ex001 {
 *   → 클래스 선언부. "public"이므로 다른 패키지에서도 접근 가능하며,
 *     파일명(Ex001.java)과 클래스명(Ex001)이 반드시 일치해야 한다.
 *
 * [원본 56행] public static void main(String[] args) {
 *   → 프로그램의 진입점. 각 키워드는 JVM이 요구하는 필수 조건이다.
 *       - public : JVM(외부)이 호출해야 하므로 접근 제한이 없어야 함
 *       - static : 객체를 생성하지 않고도(new 없이) JVM이 바로 호출해야 함
 *       - void   : 반환값이 없음
 *       - String[] args : 프로그램 실행 시 전달되는 커맨드라인 인자 배열
 *
 * [원본 58행] System.out.println("Hello JAVA!");
 *   → 콘솔(표준 출력)에 문자열을 출력하고 줄바꿈까지 수행.
 *     (println의 'ln' = line, 줄바꿈 포함이라는 뜻)
 *
 * [원본 65~70행] class Ex0000001 { }  /  class Ex00000000000001 { }
 *   → 같은 파일 안에 추가로 선언된 보조 클래스. public이 아니므로(default 접근),
 *     파일명과 이름이 달라도 되고, 이런 클래스는 파일당 여러 개 선언 가능하다.
 *     단, 이 예제에서는 내부에 아무 코드도 없어 실질적인 기능은 없다.
 *
 *
 * -------------------------------------------------------------------
 * 4. 실행 흐름
 * -------------------------------------------------------------------
 *
 * ① javac 컴파일           ② java Ex001 실행          ③ 콘솔 출력
 * ┌───────────────────┐   ┌──────────────────────┐   ┌─────────────────┐
 * │ Ex001.class         │   │ JVM이 Ex001의        │   │ Hello JAVA!      │
 * │ Ex0000001.class     │──▶│ main() 을 찾아 호출   │──▶│                  │
 * │ Ex00000000000001.class│ │ (println 실행)        │   │ (줄바꿈 포함)     │
 * └───────────────────┘   └──────────────────────┘   └─────────────────┘
 *
 * main()에 더 이상 실행할 코드가 없으므로 메서드가 종료되고, 프로그램
 * 전체가 종료된다. (Ex0000001, Ex00000000000001은 인스턴스화되지
 * 않았으므로 이번 실행에는 전혀 관여하지 않는다.)
 *
 *
 * -------------------------------------------------------------------
 * 5. Q&A (질문 - 답 - 해설)
 * -------------------------------------------------------------------
 *
 * Q1. 이 파일 안의 3개 클래스 중, "java Ex0000001" 명령으로 실행하면
 *     어떻게 될까?
 * A1. 실행되지 않고 오류가 발생한다.
 * 해설: Ex0000001에는 main() 메서드 자체가 정의되어 있지 않기 때문에
 *     "main method not found in class Ex0000001" 오류가 발생한다.
 *     클래스가 public인지 여부와 별개로, 애초에 진입점(main)이 있는
 *     클래스만 JVM 실행 대상이 될 수 있다.
 *
 * Q2. 한 개의 .java 파일 안에 public 클래스를 2개 선언하면 어떻게 될까?
 *     (예: public class Ex001 { } 와 public class Ex002 { } 를 같은
 *     파일에 함께 선언)
 * A2. 컴파일 에러가 발생한다.
 * 해설: Java 언어 규칙상 하나의 .java 소스 파일에는 public 클래스가
 *     최대 1개만 허용되고, 그 이름은 반드시 파일명과 일치해야 한다.
 *     그래서 원본 코드의 Ex0000001, Ex00000000000001은 public 키워드
 *     없이(default 접근제한자로) 선언되어 있다.
 *
 * Q3. 클래스 이름을 "2Hello" 로 지으면 어떻게 될까?
 * A3. 컴파일 에러(식별자 규칙 위반)가 발생한다.
 * 해설: Java의 식별자(변수명, 클래스명 등) 규칙상 이름은 숫자로
 *     시작할 수 없다. 숫자는 이름의 중간이나 끝에만 올 수 있으며,
 *     이는 원본 코드 상단 주석에도 명시되어 있다.
 *
 */
