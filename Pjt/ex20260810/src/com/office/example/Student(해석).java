/*
 * ===================================================================
 *  Student.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 학습용 해석 문서입니다. main 메서드가 없는 "설계도(클래스)"
 *   파일이고, Example001.java가 가져다 씁니다.
 *
 *   이 파일이 가르치려는 것:
 *   "생성자(constructor)" 한 가지입니다. 그중에서도
 *     (1) 디폴트 생성자가 뭔지
 *     (2) 디폴트 생성자 안에 필드 초기화를 넣으면 "일반 생성자"가
 *         되고, 그러면 자바가 디폴트 생성자를 자동으로 안 넣어준다는 것
 *     (3) 생성자 오버로딩 (매개변수를 받는 버전)
 *   을 순서대로 보여주는 강의 노트 성격의 파일입니다. 원본에 달린
 *   한국어 주석이 곧 강의 내용입니다.
 *
 *   컴파일 상태: 지금 이대로는 컴파일이 안 됩니다. 매개변수가 없는
 *   public Student() 가 두 번 적혀 있어서입니다. 이게 실수인지
 *   의도인지는 "1-2." 에서 따집니다.
 *
 *
 * ###################################################################
 *  0. 이 파일에 나오는 개념·용어 정리 (먼저 읽으세요)
 * ###################################################################
 *
 *  ● 클래스(class)
 *    물건을 만들기 위한 설계도. `public class Student { ... }` 는
 *    "학생 설계도" 입니다. 설계도 자체는 학생이 아닙니다.
 *
 *  ● 객체(object) / 인스턴스(instance)
 *    설계도로 실제로 찍어낸 물건 하나. `new Student(...)` 를 실행해야
 *    학생 객체 하나가 메모리에 생깁니다.
 *
 *  ● 필드(field) / 멤버 변수(member variable)
 *    객체가 안에 저장하는 값. 클래스 안, 메서드 바깥에 선언한 변수
 *    입니다(여기선 name, grade, age, major). 객체마다 자기 몫을
 *    따로 가집니다.
 *
 *  ● 기본값(default value)
 *    필드에 아무 값도 안 넣었을 때 자바가 자동으로 채워두는 값.
 *    String 은 null, int 는 0.
 *
 *  ● 생성자(constructor)
 *    `new` 로 객체를 만드는 바로 그 순간, 자바가 자동으로 한 번
 *    실행하는 코드 덩어리. "갓 만들어진 객체의 초기 세팅" 을
 *    담당합니다. 생김새로 알아보는 법:
 *      - 이름이 클래스 이름과 똑같다 (Student)
 *      - 반환타입(void, int 같은 것)을 안 적는다
 *
 *  ● 디폴트 생성자 / 기본 생성자(default constructor)
 *    매개변수가 하나도 없는 생성자: `public Student() { }`.
 *    핵심 규칙:
 *      - 개발자가 생성자를 "하나도" 안 적으면 → 자바가 텅 빈
 *        디폴트 생성자를 자동으로 하나 넣어준다.
 *      - 개발자가 생성자를 "하나라도" 직접 적으면(매개변수 있는
 *        것이든 없는 것이든) → 자바는 디폴트 생성자를 자동으로
 *        안 넣어준다. 필요하면 개발자가 직접 적어야 한다.
 *
 *  ● 일반 생성자
 *    디폴트 생성자가 아닌 생성자. 매개변수를 받거나, 본문에서 필드
 *    초기화 같은 실제 작업을 하는 생성자입니다. 원본 주석의 요지:
 *    "매개변수 없는 생성자라도, 그 안에서 필드를 초기화하기 시작하면
 *     더 이상 '텅 빈 디폴트 생성자' 라고 부르지 않고 일반 생성자라
 *     부른다."
 *
 *  ● 생성자 오버로딩(constructor overloading)
 *    이름이 같은 생성자를, 매개변수의 개수·타입만 다르게 해서 여러
 *    개 두는 것. 자바는 `new` 할 때 넘긴 인자의 개수·타입을 보고
 *    그중 맞는 것을 골라 실행합니다. (원본 주석의 "과적" 은
 *    overloading 을 직역한 말입니다.)
 *
 *  ● 중복 선언 (컴파일 에러)
 *    이름도 같고 "매개변수 목록도 완전히 같은" 생성자를 한 클래스에
 *    두 개 두는 것. 오버로딩은 매개변수 목록이 "달라야" 성립하므로,
 *    같으면 오버로딩이 아니라 중복이고 자바가 거부합니다. 본문
 *    내용이 달라도 소용없습니다 — 자바는 매개변수 목록만 봅니다.
 *
 *  ● 매개변수(parameter) / 인자(argument)
 *    매개변수 = 생성자·메서드 괄호 안에 선언한, 값을 받는 변수.
 *    인자 = 부를 때 실제로 넘기는 값.
 *    new Student("홍길동", 1, 20, "computer") 에서 "홍길동", 1,
 *    20, "computer" 가 인자입니다.
 *
 *  ● this
 *    지금 이 코드를 실행 중인 객체 자신. `this.name` 은 "이 객체의
 *    name 필드" 라는 뜻입니다.
 *
 *  ● 섀도잉(shadowing)
 *    메서드/생성자 안의 매개변수 이름이 필드 이름과 똑같을 때, 그
 *    안에서 그냥 `name` 이라고 쓰면 자바는 더 가까운 쪽(매개변수)
 *    으로 알아듣습니다. 그래서 필드가 "가려집니다". 필드를 콕
 *    집으려면 앞에 `this.` 를 붙입니다.
 *
 *  ● void
 *    "돌려주는 값이 없음" 을 뜻하는 반환타입. printInfo() 가 void 라
 *    출력만 하고 값은 안 돌려줍니다.
 *
 *
 * ###################################################################
 *  1. 코드 해석 (파일 위에서 아래로)
 * ###################################################################
 *
 *
 * // '디폴트 생성자' 라고 한다.
 * public Student() {
 * }
 *
 * // 생성자(Constructor)  <-- 기본 생성자(Default Constructor)
 * public Student() {
 *     System.out.println("Student() Constructor Called!");
 *     // ***** 이렇게 디폴트 생성자에서 멤버 필드를 초기화 하게 되면
 *     //       이제 디폴트 생성자는 더이상 디폴트 생성자가 아니게됨.
 *     //       이제부터는 일반 생성자라고 함.
 *     //       그러면 디폴트 생성자가 없으니, 컴파일러가 개발자를
 *     //       대신해서 디폴트 생성자를 넣어줄까요?
 *     //       일반 생성자가 있다면 넣어 주지 않습니다.
 *     name = "홍길동";
 *     grade = 1;
 *     age = 20;
 *     major = "computer";
 * }
 *
 *   [의도된 장치 — 다만 이대로는 컴파일 불가]
 *   이 두 개의 public Student() 는 복붙 실수가 아닙니다. 원본 주석이
 *   말해 줍니다 — "비었을 때" 와 "필드 초기화를 채웠을 때" 를 나란히
 *   놓고 개념을 비교시키려는 것입니다.
 *     - 첫 번째: 본문이 텅 빔 → 진짜 디폴트 생성자
 *     - 두 번째: 본문에 name/grade/age/major 초기화를 넣음 → 이제
 *               "디폴트 생성자" 라 부르지 않고 "일반 생성자" 라 부른다
 *   그리고 두 번째 주석의 핵심 규칙: 일반 생성자가 하나라도 생기면
 *   자바는 개발자 대신 디폴트 생성자를 자동으로 넣어주지 않는다.
 *   즉 "필드 초기화를 넣는 순간 공짜 디폴트 생성자를 잃는다" 는
 *   것을 보여주려는 노트입니다.
 *
 *   왜 컴파일이 안 되나:
 *   두 생성자는 이름(Student)도 같고 매개변수 목록(둘 다 없음)도
 *   완전히 같습니다. 그래서 자바는 "같은 생성자를 두 번 만들었다" 며
 *   중복 선언 에러를 냅니다. 본문이 다른 건 상관없습니다.
 *
 *   개념을 살린 최소 수정 (둘 중 하나를 주석 처리):
 *
 *     // public Student() {          // (텅 빈 디폴트 생성자 — 비교용)
 *     // }
 *     public Student() {             // 필드 초기화를 넣어 '일반 생성자'가 된 버전
 *         System.out.println("Student() Constructor Called!");
 *         name = "홍길동";
 *         grade = 1;
 *         age = 20;
 *         major = "computer";
 *     }
 *
 *   텅 빈 쪽을 주석으로 내리면 중복이 사라져 컴파일됩니다. 비교
 *   개념은 주석으로 남아 있습니다.
 *   (참고: 이 두 번째 생성자 안에서 name 에 this. 를 안 붙여도
 *    되는 이유 — 이 생성자에는 name 이라는 매개변수/지역변수가
 *    없어서 섀도잉이 없기 때문입니다. 그냥 name 이 곧 필드입니다.)
 *
 *
 * // 생성자 매개 변수  ==> 일반 생성자 == 생성자 오버로딩
 * // 매개변수 이름은 속성명과 동일하게 하자
 * public Student(String name, int grade, int age, String major) {
 *     System.out.println("Student() Constructor Called!");
 *     this.name = name;
 *     this.grade = grade;
 *     this.age = age;
 *     this.major = major;
 * }
 *
 *   [정상 — 생성자 오버로딩]
 *   이름은 Student 로 같지만 매개변수가 4개 있습니다. 위의 매개변수
 *   없는 생성자와 매개변수 목록이 "다르므로" 이건 정상적인 오버로딩
 *   입니다. new Student("홍길동", 1, 20, "computer") 처럼 인자 4개로
 *   부르면 이게 선택됩니다.
 *   매개변수 이름(name, grade, age, major)을 필드 이름과 똑같이
 *   맞췄습니다(원본 주석대로 가독성 목적). 그래서 이 생성자 안에서는
 *   섀도잉이 일어나고, `this.name = name;` 처럼 this. 를 붙여
 *   "매개변수 말고 이 객체의 필드에 넣어라" 라고 콕 집습니다.
 *
 *
 * String name;     // 기본값 null
 * int grade;       // 기본값 0
 * int age;         // 기본값 0
 * String major;    // 기본값 null
 *
 *   Student 객체마다 따로 갖는 필드 4개입니다. 필드를 클래스 아래쪽에
 *   적었지만 자바가 먼저 전부 읽어두므로, 위쪽 생성자에서 미리 써도
 *   문제없습니다.
 *
 *
 * public void printInfo() {
 *     System.out.println("Name :" + name);
 *     System.out.println("Grade :" + grade);
 *     System.out.println("Age :" + age);
 *     System.out.println("Major :" + major);
 * }
 *
 *   반환타입이 void 인 일반 메서드. 저장된 필드 4개를 그대로 꺼내
 *   출력합니다.
 *
 *
 * ###################################################################
 *  2. 실행하면 어떻게 될까 (중복 생성자를 정리했다고 가정, Example001 기준)
 * ###################################################################
 *
 *   Example001 은 매개변수 4개짜리 생성자만 부릅니다. 따라서 학생
 *   객체를 만들 때마다 "Student() Constructor Called!" 가 찍히고,
 *   이어서 printInfo() 가 그 학생의 네 필드를 출력합니다.
 */
