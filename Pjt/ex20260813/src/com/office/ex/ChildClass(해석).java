/*
 * ===================================================================
 *  ChildClass.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 학습용 해석 문서입니다. main 메서드가 없는 "설계도"
 *   파일이고, MainClass.java가 씁니다. 이 파일이 이 디렉토리의
 *   핵심입니다 — 본문이 텅 비어 있는데도 동작하는 이유가 상속
 *   이니까요.
 *
 *   이 파일이 가르치려는 것:
 *   "extends 로 부모 클래스를 상속하면, 자식은 자기 코드를 하나도
 *   안 써도 부모의 필드·메서드를 물려받아 자기 것처럼 쓸 수 있다."
 *
 *   컴파일 상태: 문법 오류 없이 컴파일됩니다.
 *
 *
 * ###################################################################
 *  0. 이 파일에 나오는 개념·용어 정리 (먼저 읽으세요)
 * ###################################################################
 *
 *  ● 상속(inheritance)
 *    한 클래스가 다른 클래스의 속성(필드)과 기능(메서드)을 그대로
 *    물려받는 것. 원본 주석대로 "인간 세계의 상속" 과 같은 그림입니다
 *    — 부모가 가진 것을 자식이 그대로 받습니다.
 *
 *  ● extends 키워드
 *    `class 자식 extends 부모` 라고 쓰면, 자식이 부모를 상속합니다.
 *    여기선 `class ChildClass extends ParentClass`.
 *
 *  ● 부모 클래스 / 자식 클래스 (superclass / subclass)
 *    물려주는 쪽 = 부모(ParentClass). 물려받는 쪽 = 자식(ChildClass).
 *
 *  ● 상속되는 것
 *    부모의 public(그리고 protected) 필드·메서드는 자식이 자기
 *    멤버처럼 씁니다. 여기선 ParentClass 의 print() 가 그렇게
 *    내려옵니다.
 *
 *  ● 자식 본문이 비어도 되는 이유
 *    자식이 새로 추가할 게 없으면 본문을 비워둬도 됩니다. 그 자식
 *    객체는 부모에게 물려받은 것만으로 동작합니다.
 *
 *  ● 메서드를 찾는 순서
 *    `childClass.print()` 를 부르면 자바는 먼저 ChildClass 안에서
 *    print() 를 찾고, 없으면 부모 ParentClass 로 올라가 찾습니다.
 *    여기선 ChildClass 에 없으니 ParentClass 의 print() 가 실행됩니다.
 *
 *
 * ###################################################################
 *  1. 코드 해석 (파일 전체)
 * ###################################################################
 *
 *
 * public class ChildClass extends ParentClass {
 *
 * }
 *
 *   [정상 — 이 디렉토리의 핵심]
 *   `extends ParentClass` 한 줄이 전부입니다. 본문은 텅 비어 있습니다.
 *   그런데도 ChildClass 로 만든 객체는 print() 를 부를 수 있습니다
 *   — ParentClass 에서 물려받았기 때문입니다. "자식은 아무것도
 *   안 써도 부모 것을 쓴다" 를 가장 짧게 보여주는 파일입니다.
 *
 *
 * ###################################################################
 *  2. 실행하면 어떻게 될까
 * ###################################################################
 *
 *   이 파일만으로는 실행되는 것이 없습니다(설계도, main 없음).
 *   MainClass 에서 new ChildClass().print() 를 하면, 물려받은
 *   ParentClass 의 print() 가 실행되어 "ABCEDFG!" 가 출력됩니다.
 */
