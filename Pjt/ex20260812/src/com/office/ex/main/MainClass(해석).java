/*
 * ===================================================================
 *  main/MainClass.java 해석본
 * ===================================================================
 *
 * ※ 참고 : 학습용 해석 문서입니다. 이 프로그램의 시작점(main)입니다.
 *   CoolingSystem 과 CoolingController 를 조립해서 실행시킵니다.
 *   각각 CoolingSystem(해석).java, CoolingController(해석).java 참고.
 *
 *   이 파일이 가르치려는 것:
 *   "부품을 만들어 조립하는 자리" — 에어컨(CoolingSystem)을 먼저
 *   만들고, 그것을 제어기(CoolingController)의 생성자에 넘겨준다.
 *   제어기가 쓸 에어컨을 "여기서" 만들어 넣어 주는 것이 의존성
 *   주입의 실제 모습입니다.
 *
 *   컴파일 상태: 문법 오류 없이 컴파일됩니다.
 *
 *
 * ###################################################################
 *  0. 이 파일에 나오는 개념·용어 정리 (먼저 읽으세요)
 * ###################################################################
 *
 *  ● main 메서드
 *    `public static void main(String[] args)`. 실행 시작점.
 *
 *  ● import
 *    다른 패키지 클래스를 가져오는 선언. 여기선 controller 패키지의
 *    CoolingController, system 패키지의 CoolingSystem 을 가져옵니다.
 *
 *  ● 객체를 만들어 다른 객체에 넘겨주기 (의존성 주입 조립)
 *    먼저 CoolingSystem 객체를 만들고, 그것을 CoolingController 의
 *    생성자에 인자로 넘겨 CoolingController 를 만듭니다.
 *    CoolingController 는 자기가 쓸 CoolingSystem 을 직접 안 만들고
 *    여기서 받은 것을 씁니다.
 *
 *  ● 한 문장을 여러 줄에 나눠 쓰기
 *    `CoolingSystem coolingSystem =` 다음 줄에
 *    `new CoolingSystem("white");` — 자바는 세미콜론(;)까지를 한
 *    문장으로 보므로 줄을 나눠도 상관없습니다.
 *
 *
 * ###################################################################
 *  1. 코드 해석 (파일 위에서 아래로)
 * ###################################################################
 *
 *
 * CoolingSystem coolingSystem =
 *         new CoolingSystem("white");
 *
 *   [정상]
 *   에어컨 객체를 하나 만듭니다. 인자 "white" 는 CoolingSystem
 *   생성자의 color 매개변수로 들어가 색상 필드에 저장됩니다. 이
 *   순간 생성자가 실행되어 전원 꺼짐, 희망 온도 18, 제조일 = 지금
 *   시각으로 초기화됩니다.
 *
 *
 * CoolingController coolingController =
 *         new CoolingController(coolingSystem);
 *
 *   [정상 — 의존성 주입 조립]
 *   제어기 객체를 만드는데, 방금 만든 coolingSystem 을 생성자에
 *   넘깁니다. CoolingController 는 이 에어컨을 자기 필드에 저장해
 *   두고 계속 조작합니다. 새로 만드는 게 아니라 "이미 있는 것을
 *   받아 쓴다" 는 점이 핵심입니다.
 *
 *
 * coolingController.control();
 *
 *   [정상]
 *   제어기의 control() 을 실행합니다. 여기서부터 메뉴 반복이
 *   시작됩니다 — 이후 흐름은 CoolingController(해석).java 로
 *   이어집니다.
 *
 *
 * ###################################################################
 *  2. 실행하면 어떻게 될까
 * ###################################################################
 *
 *   흰색 에어컨 하나가 만들어지고(전원 off, 18도), 제어기가 그것을
 *   받아 control() 을 돌립니다. 사용자가 3(The end)을 누를 때까지
 *   메뉴가 반복되고, 매 선택 후 상태표가 출력됩니다.
 */
