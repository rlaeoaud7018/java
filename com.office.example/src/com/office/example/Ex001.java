package com.office.example;

// 한줄 주석

/*
 * 1. class 란?
 * 
 * class(클래스)는 프로그램을 구성하는 단위.
 * 그래서 java 응용프로그램은 반드시 하나 이상의 클래스 파일이 있어야 함.
 *
 * 프로그램이란 것을 단순하게 생각해보면, 특정 기능들이 모여있는 집합체라고 할 수 있다.
 * 여기서 특정 기능들이 기술되어 있는 곳이 바로 '클래스'이다.
 * 
 * 클래스는 기본적으로 'public', 'class' 키워드(예약어)를 사용하고 다음에 '클래스명(Ex001)'을 작성한다.
 * 다음에 클래스 안에 코드의 시작과 끝은 '{...}' 를 이용한다.
 * 
 * 
 * 2. 클래스 이름 규칙
 * 
 * 클래스 이름은 java 파일명과 동일하게 한다.
 * 따라서 하나의 java 파일에는 하나의 클래스가 있는 것이 일반적이다.
 * 하지만 일반적이지 않은 경우도 있다. 하나의 java 파일에 2개 이상의 클래스 선언(예전에 메모리 아끼려고 사용했던 방식. 요즘은 인프라가 좋아져서 그냥 파일을 새로 만든다.)
 * 
 * 클래스 이름은 영문 대문자로 시작하는 것이 일반적이다.
 * 숫자를 사용하고자 할때는 중간, 끝에만 사용 가능하다. 즉 클래스 이름의 첫 글자에는 사용하지 못 한다.
 * Hello --> O
 * H2ello --> O
 * Hello2 --> O
 * 2Hello --> X
 * 
 * 일반적이지는 않지만 특수문자를 사용하는 경우가 있다. 이때 특수문자는 '$','_' 만 사용 가능하다.(달러, 언더바)
 * _Hello --> O
 * H_ello --> O
 * Hello_ --> O
 * $Hello --> O
 * H$ello --> O
 * Hello$$ --> O
 * 
 * Hello@ --> X
 * Hello^^ --> X
 * 
 * 결론적으로 특수문자, 숫자는 가급적 사용하지 말자!
 */

// 파일명과 동일하게 클래스명을 붙인다.
public class Ex001 {

	/*
	 * main 메서드(method)란? java 응용프로그램을 실행하면 JVM은 프로글매 내 많은 코드 중에서 가장 먼저 시작해야하는 코드를
	 * 찾아야 하는데, 이 때 가장 먼저 실행하는 (즉 call 하는) 코드가 바로 main 메서드 이다. 즉, JVM은 main 메서드를
	 * 프로그램의 시작점으로 생각하고 프로그램을 실행 한다.
	 * 
	 * class, main()은 코드 블럭을 '{ }' 사용하기 때문에 들여쓰기는 아무런 의미가 없다.
	 */

	public static void main(String[] args) {

		System.out.println("Hello JAVA!"); // ---console.og or print();

	}

}

